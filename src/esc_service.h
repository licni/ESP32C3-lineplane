// 版本流水號: r4 (2026-09-14) 校正旗標時效 10 分鐘 → 10 秒(GG)
// 舊: r3 (2026-09-14) 校正旗標時效 10 分鐘,軟體重開取消
// 舊: r2 (2026-09-14) 開機是否允許上電自動倒數(只認上電重置,GG);測試旗標 powerontest
// 舊: r1 (2026-09-13) 初版:電變校正旗標(下次通電進入校正)
#pragma once
#include <Arduino.h>
// ============================================================================
// 電變校正精靈的「下次通電進入校正」旗標. 存在獨立的 NVS 命名空間 lpesc,不放進飛行設定結構
// (不算未儲存變更,也不會被「回預設」洗掉).
//
// 為什麼只認「上電重置」:校正時開機第一件事輸出最高油門. 如果是軟體重開(網頁重開機,OTA,
// 當機重開,電壓不足重置),電變很可能早就通電解鎖了,最高油門等於馬達全速. 所以只有冷開機
// (電池一接上,板子與電變一起通電)才消耗旗標;其他重開方式保留旗標,等真正通電.
// ============================================================================

// 開機時呼叫一次(在 escBegin 之前). 讀旗標;是上電重置就清掉旗標並回傳 true.
bool escCalibTakeAtBoot();
// 目前旗標(RAM 快取,網頁顯示用).
bool escCalibPending();
// 設定/取消旗標(寫 NVS). 成功回 nullptr.
const char *escCalibSetPending(bool on);
// 旗標時效(GG 2026-09-14 安全審查 A4):設定後通電超過這麼久沒拔電就自動取消;軟體重開也取消.
// GG 定 10 秒(原本 10 分鐘):按下後馬上拔電才算數,忘記就取消. 網頁按鈕旁有醒目說明.
// 限制:斷電期間沒有時鐘,「設定後 10 秒內拔電,放幾天再接電」仍會校正.
// 不加「開機時安全開關要按下」的條件(GG:會影響電變上電當下看到最高油門的時序).
const uint32_t ESC_CALIB_EXPIRE_MS = 10UL * 1000UL;
// loop 呼叫:檢查時效
void escCalibTick(uint32_t nowMs);
// 旗標自動取消剩餘秒數(-1 = 沒有旗標)
float escCalibExpireRemainS(uint32_t nowMs);
// 測試用(USB 序列指令 calexp):這次開機的時效改成 sec 秒
void escCalibTestSetExpire(uint32_t sec);
// 這次開機的重置原因是不是上電(網頁提示用).
bool escBootWasPowerOn();
// 這次開機能不能「上電後直接倒數」(GG 2026-09-14):只有真的拔電再接電才可以.
// OTA 更新完,網頁重開機,當機或電壓不足重開都不自動倒數:旁邊可能沒有人(遠端更新),或飛機正拿在手上.
// 要在 escCalibTakeAtBoot() 之後呼叫.
bool escBootAllowsAutoStart();
// 測試用(只有 USB 序列指令 powerontest 會呼叫):下一次軟體重開也允許自動倒數. 桌上 USB 供電沒辦法真的斷電.
bool escPowerOnTestArm();
