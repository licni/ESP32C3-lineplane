// 版本流水號: r4 (2026-09-14) 加起飛安全開關 GPIO21(GG:微動開關接地才能開始起飛倒數)
// 舊: r3 (2026-09-13) 加機輪收腳舵機 GPIO3
// 舊: r2 (2026-09-13) I2C 改 GPIO0/1(配合 GG 開發板實際接線,scanall 掃到)
#pragma once
#include <Arduino.h>
// ============================================================================
// 線控飛機油門控制器:腳位與硬體常數. 使用者依自己硬體修改的項目集中在這裡.
// ============================================================================

// --- 電變訊號輸出 ------------------------------------------------------------
// 電變訊號線在斷電,上電,重置,燒錄全程都不允許出現自發脈衝:舵機收到毛刺只會抖一下,
// 電變收到卻可能讓馬達轉起來. GPIO4 在重置期間是純輸入,沒有上拉,不產生毛刺.
// 避開 GPIO2/8/9(開機模式判斷腳)與 GPIO21(U0TXD,重置時 ROM 會從這腳送開機訊息).
const uint8_t PIN_ESC_SIGNAL = 4;

// --- 機輪收腳舵機(GG 2026-09-13)--------------------------------------------------
// GPIO3 不是開機模式判斷腳,重置與燒錄期間是輸入,不會送出亂脈衝讓舵機抖動.
const uint8_t PIN_GEAR_SERVO = 3;

// --- 起飛安全開關(GG 2026-09-14 安全審查後決定)-----------------------------------------
// 微動開關一端接 GPIO21,一端接地. 內部上拉:沒按 = 高電位 = 不能開始起飛程序;按下 = 低電位 = 可以.
// 沒接開關或線斷掉都是高電位,一樣不能起飛(安全側). 上電自動倒數與推飛機手勢都要看它.
// GPIO21 是 U0TXD:本板序列埠走原生 USB,這隻腳空著;但重置後最初幾十毫秒 ROM 會把它當輸出拉高送開機訊息,
// 開關這時按著等於瞬間短路,建議開關串 1kΩ 電阻再接地.
const uint8_t PIN_ARM_SWITCH = 21;

// --- MPU6050 I2C -------------------------------------------------------------
// 上拉靠模組自帶的電阻(常見 4.7k). 模組若沒有上拉,需外接 4.7k~10k 到 3V3.
// GG 的開發板實際接在 GPIO0/1(2026-09-13 用 scanall 指令掃到). I2C 閒置為高電位,
// 開機瞬間的電位變化對感測器無害,放哪兩隻腳都可以;接在別處改這兩行即可.
const uint8_t PIN_I2C_SDA = 0;
const uint8_t PIN_I2C_SCL = 1;

// --- 板載狀態燈 ----------------------------------------------------------------
// SuperMini 板上的藍色 LED 接在 GPIO8,低電位亮. GPIO8 是開機模式判斷腳,
// 開機時要維持高電位 —— LED 本身經電阻接到 3V3 正好把它拉高,開機後當輸出用沒有問題.
const uint8_t PIN_STATUS_LED = 8;
const bool STATUS_LED_ACTIVE_LOW = true;

// 燒錄防呆:Serial 必須走原生 USB. platformio.ini 的 build_flags 已設定,少了就讓編譯失敗.
#if !defined(ARDUINO_USB_CDC_ON_BOOT) || (ARDUINO_USB_CDC_ON_BOOT == 0)
#error "ARDUINO_USB_CDC_ON_BOOT must be 1 (see platformio.ini build_flags)"
#endif
